// Renders eval/e5/GUARD-PROFILE.md from the raw files in eval/results/E5/guard-profile/.
// Every number here is computed from those files; nothing is typed in by hand except the prose.
import path from 'node:path';
import { analyze, med, sec, sum } from './profile-guard.js';

const pct = (a, b) => (b ? `${Math.round((100 * a) / b)}%` : '–');
const rangeS = (xs) => {
  const v = xs.filter((x) => Number.isFinite(x)).sort((a, b) => a - b);
  return v.length ? `${sec(med(v))} (${sec(v[0])}–${sec(v[v.length - 1])}, n=${v.length})` : '–';
};

export function renderProfile(files, { notes = [] } = {}) {
  const runs = files.map(({ file, raw }) => ({ file, raw, a: analyze(raw) }));
  const L = [];
  L.push('# Test guard profile (E5 part 2)');
  L.push('');
  L.push('Generated by `node eval/e5/profile-guard.js --report` from the raw files in `eval/results/E5/guard-profile/` (one JSON per run). Each run is a scratch clone of this repo at a real commit\'s parent with that commit\'s changes staged (everything but `.proof/`), and `pocp fix` run on it in-process, exactly as an agent would. POCP\'s process runner is wrapped to timestamp each check run; the log name POCP gives each run says what it was. Nothing in POCP is changed by the wrapper.');
  L.push('');
  if (!runs.length) return `${L.join('\n')}\nNo runs yet.\n`;
  const r0 = runs[0].raw;
  L.push(`Machine: ${r0.cpu_model}, ${r0.cpus} CPUs, ${r0.pins.os}, Node ${r0.pins.node}. Scenarios: ${[...new Set(runs.map((r) => r.a.commit))].map((c) => `\`${c}\``).join(', ')} (each edits \`test/e2e-guard-mechanical.test.js\`; required checks \`unit-tests\`, \`engine-tests\`, \`test-suite\` = \`npm test\`, 10 mutants, seed 1).`);
  L.push('');
  L.push('**Machine load.** The Mac was shared with other agents\' work throughout (1-minute load average, sampled every 10 s, in each table). On 8 CPUs, a load of 40+ means every check ran several times slower than it would alone; the absolute times below are this machine under this load, not POCP\'s speed. The *shares* and *counts* are what carry over.');
  L.push('');
  for (const n of notes) L.push(n, '');

  // Headline numbers from the runs of the previous guard that ran to a verdict without timeouts.
  const prev = runs.filter((r) => /^before/.test(r.a.label) && r.a.verdict && !r.raw.runs.some((x) => x.timed_out));
  if (prev.length) {
    const share = (f) => prev.map((r) => `${pct(f(r.a), r.a.guard_ms)}`).join(', ');
    L.push('## What this shows');
    L.push('');
    L.push(`From the ${prev.length} completed runs of the previous guard (${prev.map((r) => `\`${r.a.commit}\``).join(', ')}):`);
    L.push('');
    L.push(`- **The guard is almost all check runs.** Snapshots, copies, restoring old tests and building the mutation plan take about a second in total (setup gaps below; a tree snapshot is ${sec(med(prev.flatMap((r) => r.a.microbench.tree_snapshot_ms)))}, a copy ${sec(med(prev.flatMap((r) => r.a.microbench.copy_snapshot_ms)))}). Reusing snapshots or caching plans can't matter.`);
    L.push(`- **The old-tests baseline ran alone:** ${share((a) => a.old_baseline_span_ms)} of guard wall time, one check at a time, with the other job slots idle. The new-code baseline was already reused from the plain proofs in every run.`);
    L.push(`- **The full suite dominates the mutant phase:** ${prev.map((r) => pct(r.a.full_suite_ms, r.a.mutant_check_ms)).join(', ')} of mutant check-seconds. Mutants that reached it on the old side: ${prev.map((r) => `${r.a.reached_last_check_old} of ${r.a.sampled}`).join(', ')}. Every mutant the old tests miss runs all three checks; every one only the suite catches runs all three on the old side and, before this change, all three again on the new side.`);
    L.push(`- **Overlap:** the suite (\`node --test test/*.test.js\`) contains the unit and engine test files, so those ran twice in each copy that reached it: ${prev.map((r) => sec(r.a.full_suite_ms ? r.a.mutants.reduce((acc, m) => acc + [m.old, m.new].reduce((x, sd) => { const i = sd.ran.findIndex((y) => y.check === 'test-suite'); return x + (i > 0 && sd.ran.slice(0, i).every((y) => !y.failed) ? sd.ran.slice(0, i).reduce((z, y) => z + y.ms, 0) : 0); }, 0), 0) : 0)).join(', ')} of check time. Skipping the faster checks when the suite will run anyway would be safe only if the suite provably runs a superset of their tests, which POCP can't know from two shell commands; not done.`);
    L.push(`- **Parallelism:** ${r0.cpus} CPUs; the guard runs up to ${Math.min(4, r0.cpus - 1)} mutant checks at once (min(4, CPUs − 1)), and achieved ${prev.map((r) => r.a.mutant_concurrency?.avg.toFixed(1)).join(', ')} on average in the mutant phase. The phase ends with one or two slow mutants (caught only by the suite) running alone, so more jobs would not shorten it; \`node --test\` already runs test files in parallel inside each check.`);
    const tos = runs.filter((r) => r.raw.runs.some((x) => x.timed_out));
    if (tos.length) {
      L.push(`- **Load can change mutant outcomes.** ${tos.length} run(s) had checks hit the ${(tos[0].raw.timeout_ms || 600000) / 60000}-minute check timeout (${tos.map((r) => `\`${path.basename(r.file, '.json')}\`: ${r.raw.runs.filter((x) => x.timed_out).map((x) => (x.phase === 'mutant' ? `m${x.mutant} ${x.side} ${x.check}` : `${x.phase} ${x.check}`)).join(', ')}`).join('; ')}). The guard counts a mutant whose check times out as caught, so on a loaded machine a mutant the suite would miss can count as caught on the old side (raising the bar the new tests must meet), and a timed-out baseline makes the verdict inconclusive. Those runs are excluded from the before/after medians; the later rounds raised the scratch clone's timeout to 60 minutes (committed on top of the parent, so the base has it too).`);
    }
    L.push(`- **The critical path** is the slowest mutant: unit → engine → suite on the old side, then, before this change, unit → engine → suite again on the new side. Killer-first cuts that second chain to the suite alone.`);
    L.push('');
  }

  L.push('## Every run');
  L.push('');
  L.push('| Run | Label | Scenario | Started | Load (median / max) | Total `pocp fix` | Plain proofs | Guard | Verdict | Old tests caught | Timed-out checks |');
  L.push('|---|---|---|---|---|---|---|---|---|---|---|');
  for (const { file, a } of runs) {
    L.push(`| \`${path.basename(file, '.json').slice(0, 40)}\` | ${a.label} | \`${a.commit}\` | ${a.started_at.slice(0, 16)} | ${a.load_median?.toFixed(0)} / ${a.load_max?.toFixed(0)} | ${sec(a.total_ms)} | ${sec(sum(a.plain.map((p) => p.ms)))} | ${sec(a.guard_ms)} | ${a.verdict} | ${a.old_caught} of ${a.sampled} | ${runs.find((r) => r.a === a).raw.runs.filter((r) => r.timed_out).length} |`);
  }
  L.push('');

  L.push('## Where the guard\'s time goes');
  L.push('');
  L.push('Wall time of the guard, split by phase (from the run timeline). "Setup" is everything between the guard\'s start and its first check run plus the gap between the old-tests baseline and the first mutant: tree snapshots, copies, restoring the old tests, building the mutation plan.');
  L.push('');
  L.push('In `after` runs the mutant phase starts with the old-tests baseline and overlaps it, so the phase shares add to more than 100%, and "checks in flight" counts only mutant checks (the baseline holds one more job slot while it runs).');
  L.push('');
  L.push('| Run | Guard | New-code baseline | Old tests on new code | Base run | Setup gaps | Mutant phase | Mutant check-seconds | Avg / peak checks in flight |');
  L.push('|---|---|---|---|---|---|---|---|---|');
  for (const { file, a } of runs) {
    const nb = sum(a.new_baseline.map((x) => x.ms));
    const ob = a.old_baseline_span_ms || 0;
    const br = sum(a.base_runs.map((x) => x.ms));
    const setup = Math.max(0, (a.guard_ms || 0) - nb - ob - br - (a.mutant_phase_ms || 0));
    L.push(`| \`${path.basename(file, '.json').slice(0, 24)}\` | ${sec(a.guard_ms)} | ${a.new_baseline_reused ? `reused (${a.new_baseline_reused} checks)` : sec(nb)} | ${sec(ob)} (${pct(ob, a.guard_ms)}) | ${a.base_runs.length ? sec(br) : 'not run'} | ${sec(setup)} (${pct(setup, a.guard_ms)}) | ${sec(a.mutant_phase_ms)} (${pct(a.mutant_phase_ms, a.guard_ms)}) | ${sec(a.mutant_check_ms)} | ${a.mutant_concurrency ? `${a.mutant_concurrency.avg.toFixed(1)} / ${a.mutant_concurrency.peak}` : '–'} |`);
  }
  L.push('');

  L.push('### Per check');
  L.push('');
  L.push('Duration of each check where it ran: as a plain proof, in the old-tests baseline, and per mutant run (median (min–max, n) over all runs listed).');
  L.push('');
  const checks = [...new Set(runs.flatMap(({ raw }) => raw.runs.map((r) => r.check)))];
  L.push('| Check | Plain proof | Old tests on new code | In a mutant run (old side) | In a mutant run (new side) | Share of mutant check-seconds |');
  L.push('|---|---|---|---|---|---|');
  const allMut = runs.flatMap(({ raw }) => raw.runs.filter((r) => r.phase === 'mutant'));
  const totalMut = sum(allMut.map((r) => r.end_ms - r.start_ms));
  for (const c of checks) {
    const pick = (f) => runs.flatMap(({ raw }) => raw.runs.filter((r) => r.check === c && f(r)).map((r) => r.end_ms - r.start_ms));
    const m = sum(allMut.filter((r) => r.check === c).map((r) => r.end_ms - r.start_ms));
    L.push(`| ${c} | ${rangeS(pick((r) => r.phase === 'plain'))} | ${rangeS(pick((r) => r.phase === 'guard-old'))} | ${rangeS(pick((r) => r.phase === 'mutant' && r.side === 'old'))} | ${rangeS(pick((r) => r.phase === 'mutant' && r.side === 'new'))} | ${pct(m, totalMut)} |`);
  }
  L.push('');

  L.push('### Mutants: which checks ran and which one caught it');
  L.push('');
  L.push('Checks run per mutant, in order, on the old side then (only if caught) the new side. ✗ = the check failed (caught), ✓ = passed. Times in seconds.');
  L.push('');
  for (const { file, a } of runs) {
    L.push(`**\`${path.basename(file, '.json')}\`** (${a.label}, \`${a.commit}\`, verdict ${a.verdict})`);
    L.push('');
    L.push('| # | Mutant | Old side | New side | Outcome |');
    L.push('|---|---|---|---|---|');
    const fmt = (s) => (s.ran.length ? s.ran.map((x) => `${x.check} ${x.failed ? '✗' : '✓'} ${(x.ms / 1000).toFixed(0)}`).join(' → ') : '–');
    for (const m of a.mutants) L.push(`| ${m.i} | \`${m.file}:${m.line}\` ${m.operator} | ${fmt(m.old)} | ${fmt(m.new)} | ${m.outcome} |`);
    L.push('');
    L.push(`Reached the last check (\`test-suite\`): ${a.reached_last_check_old} of ${a.sampled} on the old side, ${a.reached_last_check_new} on the new side. Full-suite runs: ${a.full_suite_runs}, ${sec(a.full_suite_ms)} of ${sec(a.mutant_check_ms)} mutant check-seconds (${pct(a.full_suite_ms, a.mutant_check_ms)}).`);
    L.push('');
  }

  L.push('## Overlap between checks');
  L.push('');
  L.push('`test-suite` is `npm test`, i.e. `node --test test/*.test.js`, which includes the files `unit-tests` and `engine-tests` run. So every mutant that gets past the two faster checks runs their tests twice, and every one the old tests miss runs all three. The table counts the full-suite runs that came after both faster checks had already passed in the same copy, and the time those two checks took in that copy (their tests ran again inside the suite).');
  L.push('');
  L.push('| Run | Full-suite runs after both faster checks passed | Time of the faster checks in those copies (re-run inside the suite) | Share of mutant check-seconds |');
  L.push('|---|---|---|---|');
  for (const { file, a } of runs) {
    let n = 0;
    let dup = 0;
    for (const m of a.mutants) {
      for (const s of [m.old, m.new]) {
        const i = s.ran.findIndex((x) => x.check === 'test-suite');
        if (i > 0 && s.ran.slice(0, i).every((x) => !x.failed)) {
          n++;
          dup += sum(s.ran.slice(0, i).map((x) => x.ms));
        }
      }
    }
    L.push(`| \`${path.basename(file, '.json').slice(0, 24)}\` | ${n} | ${sec(dup)} | ${pct(dup, a.mutant_check_ms)} |`);
  }
  L.push('');

  L.push('## Estimates from the profile (before the speedups)');
  L.push('');
  L.push('Two schedule changes that keep every result identical, estimated from the timelines above. Check-seconds are summed check run times; wall time is what the person waits.');
  L.push('');
  L.push('| Run | Old-tests baseline alone (wall), other job slots idle | New-side check time before the old side\'s catching check (killer-first saves this) |');
  L.push('|---|---|---|');
  for (const { file, a } of runs.filter((r) => !/after/.test(r.a.label))) {
    L.push(`| \`${path.basename(file, '.json').slice(0, 24)}\` | ${sec(a.old_baseline_span_ms)} | ${sec(a.killer_first_saving_check_ms)} |`);
  }
  L.push('');

  const paired = runs.filter((r) => /-paired$/.test(r.a.label));
  if (paired.length) {
    L.push('## Before and after, measured');
    L.push('');
    L.push('Each round runs the previous guard (`before`, the code at `eval/foundation`) and the new one (`after`) at the same time, in one process, on separate scratch clones of the same scenario, the start order alternating by round. Running them together means both see the same outside load, which on this machine moved by a factor of several within minutes; it also means each slows the other, so absolute times are higher than either alone.');
    L.push('');
    L.push('| Scenario | Round | Load (median) | Guard before | Guard after | Change | Total before | Total after | Same result |');
    L.push('|---|---|---|---|---|---|---|---|---|');
    const groups = new Map();
    for (const r of paired) {
      const k = r.raw.pair;
      if (!groups.has(k)) groups.set(k, {});
      groups.get(k)[r.a.label.replace(/-paired$/, '')] = r;
    }
    const deltas = {};
    let round = 0;
    for (const [, g] of [...groups].sort()) {
      if (!g.before || !g.after) continue;
      round++;
      const b = g.before.a;
      const a = g.after.a;
      const timedOut = [g.before, g.after].some((x) => x.raw.runs.some((r) => r.timed_out));
      // With a timeout override, early clones committed it at different times, so the base sha
      // differs between the two clones; its tree is the same. Compare everything else.
      const guardOf = (x) => ({ ...stripTimes(x.raw.proofs.find((p) => p.kind === 'guard')?.guard), ...(x.raw.timeout_ms ? { base: 'timeout-commit' } : {}) });
      const same = JSON.stringify(guardOf(g.before)) === JSON.stringify(guardOf(g.after));
      if (!timedOut) (deltas[b.commit] ||= []).push([b.guard_ms, a.guard_ms]);
      L.push(`| \`${b.commit}\` | ${round}${timedOut ? ' (a check timed out: verdict set by load, not counted)' : ''}${g.before.raw.timeout_ms ? ` (timeout ${g.before.raw.timeout_ms / 60000} min)` : ''} | ${b.load_median?.toFixed(0)} | ${sec(b.guard_ms)} | ${sec(a.guard_ms)} | ${pct(a.guard_ms - b.guard_ms, b.guard_ms)} | ${sec(b.total_ms)} | ${sec(a.total_ms)} | ${same ? 'yes' : '**no**'} |`);
    }
    L.push('');
    for (const [c, ds] of Object.entries(deltas)) {
      L.push(`\`${c}\`: median guard ${sec(med(ds.map((d) => d[0])))} before, ${sec(med(ds.map((d) => d[1])))} after, over ${ds.length} round(s); median per-round change ${pct(med(ds.map((d) => d[1] - d[0])), med(ds.map((d) => d[0])))}.`);
      L.push('');
    }
    L.push('"Same result" compares the two guard result objects with every duration removed: verdict, summary, every check run and exit, the mutants sampled and caught/missed on each side.');
    L.push('');
  }

  L.push('## Speedups considered');
  L.push('');
  L.push('The rule: a change ships only if every verdict and every mutant outcome stays identical for the same inputs (same mutants sampled with the same seed, same caught/missed on each side, same verdict). `test/e2e-guard-equivalence.test.js` runs a frozen copy of the previous guard (`test/guard-v0/`) and the new one on fixtures that reach every verdict (passed, detection-dropped, behavior-changed, baseline-red, inconclusive), with several seeds, mutant budgets and job counts, and requires the full result objects to be equal once durations are removed. The fixtures include mutants caught only by a slower check, so the new schedule is exercised, and two more tests check that it is (killer-first order; mutants running during the baseline within the job limit and stopping at its first failure). The paired runs above compare the real result objects too.');
  L.push('');
  L.push('| Candidate | Done? | Why |');
  L.push('|---|---|---|');
  L.push('| Start mutants alongside the old-tests baseline, sharing the job limit | **yes** | The baseline ran one check at a time for a third or more of the guard. Mutant results are used only if both baselines pass; from the first old-tests failure every mutant stops before its next check and is discarded. Check order now comes from the new-code baseline\'s (or the reused plain proofs\') durations instead of the old-tests baseline\'s; the previous guard already ordered by measured durations, which vary run to run, so it already relied on a check\'s result not depending on which checks ran before it in the same copy. |');
  L.push('| Killer-first on the new side | **yes** | A mutant is caught if any check fails, so running first the check that caught it on the old side changes only how soon that is known. On the slowest mutant it removes a unit + engine run from the critical path. Same assumption as above. |');
  L.push('| Fastest-first order on the old side | kept | Unit tests cost seconds and caught 6 of the 7 caught mutants in `ca3e9f6`; putting a slower check first would cost minutes on those. |');
  L.push('| Skip a check whose tests the suite also runs | no | Not provable from two shell commands; the task rules it out unless provable. It is the largest remaining overlap (see above). |');
  L.push('| Reuse snapshots / cache the plan | no | Setup is about a second of a 20+ minute guard. |');
  L.push('| Cache check results by code hash | no | Within one guard every mutant tree is different, the new-code baseline is already reused from the plain proofs, and whole guard results are already cached by subject. |');
  L.push('| Avoid redundant base runs | no | The base run happens only when the old tests fail on the new code, and only for the checks that failed; nothing to cut. |');
  L.push('| More jobs | no | The tail is one or two slow mutants running alone; extra slots would sit idle. Under outside load it would also raise the chance of the timeouts above. |');
  L.push('| Speculatively start a caught-looking mutant\'s new side before its old side finishes | not tried | Would shorten the critical path further using idle slots at the tail, with results discarded when the old side misses. More moving parts; left as a candidate. |');
  L.push('');

  L.push('## Snapshot costs (measured separately, same clone, after each run)');
  L.push('');
  L.push(`Tree snapshot of the staged index: ${rangeS(runs.flatMap((r) => r.a.microbench.tree_snapshot_ms))}. Copy of a snapshot (one per mutant per side, one per baseline): ${rangeS(runs.flatMap((r) => r.a.microbench.copy_snapshot_ms))}. A guard with 10 mutants makes about 2 tree snapshots and up to 22 copies.`);
  L.push('');
  return `${L.join('\n')}\n`;
}

function stripTimes(x) {
  if (Array.isArray(x)) return x.map(stripTimes);
  if (x && typeof x === 'object') {
    const o = {};
    for (const k of Object.keys(x).sort()) if (k !== 'duration_ms') o[k] = stripTimes(x[k]);
    return o;
  }
  return x;
}
